using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;

namespace TesmioAutoload
{
    // What the next game start will do. One step per plugin the loader will load, in the order
    // it will happen, plus the dependencies that come too late in that order - the trap behind
    // "my translation key is not resolved": the loader takes the plugins by name, and a service
    // only exists once its provider's init has run.
    public sealed class LoadStep
    {
        public string Name="",Target="",Key="",Dll="";
        // The DLL lies below the Workshop folder, not in <loader>\plugins.
        public bool Workshop;
        public int Index;
    }

    // A building line naming a resource that nothing publishes (see Startup.MissingResources).
    public sealed class MissingResource
    {
        public string Plugin="",Section="",Resource="",Line="";
        // 0.6.12: a folder under media_soviet\workshop_wip instead of a declaration: Plugin is its
        // display name, Section its number; Own = generated by Buildings Plus.
        public bool Folder,Own;
    }

    // A plugin that is switched on and lacks something it says it needs: Reason is "missing"
    // (nothing found for the dependency), "version" (found, but too old or too new) or "off"
    // (found, but switched off or not provided).
    public sealed class UnmetNeed
    {
        public CatalogEntry Entry;
        public Dependency Dependency;
        public string Reason="";
    }

    public static class Startup
    {
        // The loader sorts every plugin DLL it finds by its key - the file name without ".dll",
        // letters compared without case - and loads the ones that tesmioloader.ini does not
        // switch off, in that order, wherever the file lies.
        public static List<LoadStep> Order(string build,IEnumerable<CatalogEntry> entries)
        {
            var list=new List<LoadStep>();
            var known=(entries??new CatalogEntry[0]).Where(e=>e.Kind!="content"&&e.Key.Length>0&&e.Dll.Length>0).ToList();
            if(known.Count==0)return list;
            Dictionary<string,bool> switches;
            try{switches=LoaderFiles.Switches(build,known.Select(e=>e.Key));}catch(Exception){return list;}
            if(!LoaderFiles.PluginsAllowed(build))return list;
            known.Sort((a,b)=>PluginScan.CompareKeys(a.Key,b.Key));
            foreach(CatalogEntry entry in known)
            {
                if(!switches[entry.Key]||!File.Exists(entry.Dll))continue;
                if(list.Any(s=>PluginScan.SameKey(s.Key,entry.Key)))continue;
                list.Add(new LoadStep{Target=entry.Key,Key=entry.Key,Dll=entry.Dll,Workshop=!entry.Installed&&entry.Origin!="loader",Name=String.IsNullOrEmpty(entry.Name)?entry.Key:entry.Name});
            }
            for(int i=0;i<list.Count;i++)list[i].Index=i;
            return list;
        }

        // Every plugin that will load and lacks one of its declared dependencies.
        public static List<UnmetNeed> Unmet(string build,IEnumerable<CatalogEntry> entries)
        {
            var result=new List<UnmetNeed>();
            var known=(entries??new CatalogEntry[0]).ToList();
            var steps=Order(build,known);
            foreach(CatalogEntry entry in known.Where(e=>e.Dependencies.Count>0&&e.Kind!="content"))
            {
                if(StepOf(steps,entry)==null)continue;
                foreach(Dependency dependency in entry.Dependencies)
                {
                    string reason=!dependency.Found?"missing":!dependency.VersionOk?"version":!RuntimeGuard.Provisioned(build,dependency)?"off":"";
                    if(reason.Length>0)result.Add(new UnmetNeed{Entry=entry,Dependency=dependency,Reason=reason});
                }
            }
            return result;
        }

        // Switches the given plugins off in tesmioloader.ini, in one transaction.
        public static void SwitchOff(string build,IEnumerable<string> keys,Action guard)
        {
            var switches=new Dictionary<string,bool>(StringComparer.OrdinalIgnoreCase);
            foreach(string key in keys)if(!String.IsNullOrEmpty(key))switches[key]=false;
            if(switches.Count==0)return;
            string path=LoaderFiles.IniPath(build);
            var before=new Dictionary<string,string>(StringComparer.OrdinalIgnoreCase){{path,SafeFiles.HashFile(path)}};
            var writes=new Dictionary<string,byte[]>(StringComparer.OrdinalIgnoreCase){{path,LoaderFiles.Render(build,switches)}};
            Transaction.Apply(build,"start-check",writes,before,guard);
        }

        // Dependencies that load after the plugin that needs them. Returns pairs (needs, provider)
        // as ids, so the window can name both without knowing how they were found.
        public static List<KeyValuePair<string,string>> LateDependencies(List<LoadStep> steps,IEnumerable<CatalogEntry> entries)
        {
            var late=new List<KeyValuePair<string,string>>();
            if(steps==null||steps.Count==0)return late;
            var known=(entries??new CatalogEntry[0]).ToList();
            foreach(CatalogEntry entry in known)
            {
                LoadStep mine=StepOf(steps,entry);
                if(mine==null)continue;
                foreach(Dependency dependency in entry.Dependencies)
                {
                    // The catalog has resolved the dependency to the plugin that provides it.
                    if(!dependency.Found||dependency.Target.Length==0)continue;
                    LoadStep other=steps.FirstOrDefault(s=>PluginScan.SameKey(s.Key,dependency.Target));
                    if(other==null||other.Index<=mine.Index)continue;
                    late.Add(new KeyValuePair<string,string>(entry.Name,other.Name));
                }
            }
            return late;
        }
        // 0.5.13: a building line that names a resource no plugin publishes crashes the game while
        // it reads the building types - ResourceGet answers null and the storage parser reads the
        // record anyway (seen: "ResourceGet - not found road_salt", then an access violation at
        // SOVIET64+0x117B81). Vanilla Buildings and Buildings Plus are the two places a player
        // writes such lines; both are read from their effective INI in plugins\ and only when the
        // plugin loads at all. The resource set is the base game's 57 names plus whatever the
        // resources plugin (or its fork) publishes.
        public static List<MissingResource> MissingResources(string build,List<LoadStep> steps)
        {
            var result=new List<MissingResource>();
            try
            {
                string root=Path.GetFullPath(build);
                var known=new HashSet<string>(ResourceCatalogData.Templates.Select(t=>t.Name),StringComparer.OrdinalIgnoreCase);
                try{var registry=ResourceRegistry.Load(root,"resources","list","resources","hook","2");if(registry.Ready)foreach(var option in registry.Options)known.Add(option.Id);}catch(Exception){}
                CollectBuildingLines(root,steps,name=>!known.Contains(name)&&!GameOwnName(name),result);
            }
            catch(Exception){}
            return result;
        }
        // 0.6.12: the buildings that name one resource - asked before that resource is hidden or
        // removed, because the game stops at start as soon as it reads one of them without it.
        public static List<MissingResource> BuildingsNaming(string build,List<LoadStep> steps,string resourceId)
        {
            var result=new List<MissingResource>();
            if(String.IsNullOrEmpty(resourceId))return result;
            try{CollectBuildingLines(Path.GetFullPath(build),steps,name=>name.Equals(resourceId,StringComparison.OrdinalIgnoreCase),result);}
            catch(Exception){}
            return result;
        }
        // 0.7.1: the rule sets of Vanilla Buildings that will not reach every target at the next
        // start. A command whose anchor does not stand in a target exactly once makes the plugin
        // drop the whole rule set for that target; it only says so in the log, and the game runs
        // on as if the rule set were not there. Read from the file the plugin reads, and only
        // when the plugin loads and the rule set is switched on.
        public static List<RuleSpread> RuleSpreads(string build,List<LoadStep> steps,string workshopRoot)
        {
            var result=new List<RuleSpread>();
            try
            {
                string root=Path.GetFullPath(build);
                LoadStep vb=StepFor(steps,"vanilla_buildings");
                if(vb==null)return result;
                string path=SafeFiles.Child(root,"plugins\\vanilla_buildings.ini");
                if(!File.Exists(path)&&vb.Dll.Length>4)path=vb.Dll.Substring(0,vb.Dll.Length-4)+".ini";
                if(!File.Exists(path))return result;
                LooseIni ini=new LooseIni(SafeFiles.Text(path));
                string[] reserved={"general","vanilla_buildings"};
                foreach(string own in reserved)if((ini.Get(own,"enabled")??"1").Trim()=="0")return result;
                foreach(string section in ini.SectionNames())
                {
                    string name=section.Trim();
                    if(name.Length==0||reserved.Any(r=>r.Equals(name,StringComparison.OrdinalIgnoreCase)))continue;
                    if((ini.Get(name,"enabled")??"1").Trim()=="0")continue;
                    RuleSpread spread=TargetPlan.Spread(ini.GetAll(name,"target"),file=>GameBuildings.TargetLines(root,workshopRoot,file),
                        ini.GetAll(name,"add"),ini.GetAll(name,"replace"),ini.GetAll(name,"remove"),ini.GetAll(name,"insert"),
                        ini.GetAll(name,"add_connection"),ini.GetAll(name,"replace_connection"),ini.GetAll(name,"remove_connection"));
                    if(!spread.Trouble)continue;
                    spread.Plugin=vb.Name;spread.Section=name;result.Add(spread);
                }
            }
            catch(Exception){}
            return result;
        }
        // "waste" and the "waste_..." family are no resources of the list: the game's own
        // building types name them (incinerator, separation plants) and it reads them without
        // a record - its log says "ResourceGet - not found waste" at every start.
        static bool GameOwnName(string name)
        {
            return name.Equals("waste",StringComparison.OrdinalIgnoreCase)||name.StartsWith("waste_",StringComparison.OrdinalIgnoreCase);
        }
        // The declarations of the two plugins a player writes building lines for, then the
        // folders under media_soviet\workshop_wip.
        static void CollectBuildingLines(string root,List<LoadStep> steps,Func<string,bool> wanted,List<MissingResource> result)
        {
            LoadStep vb=StepFor(steps,"vanilla_buildings"),bp=StepFor(steps,"buildings_plus");
            if(bp!=null)ScanLines(root,"buildings_plus",bp,new[]{"buildings_plus","buildings"},new[]{"line","add","insert","replace"},wanted,result);
            if(vb!=null)ScanLines(root,"vanilla_buildings",vb,new[]{"general"},new[]{"add","insert","replace"},wanted,result);
            ScanGenerated(root,wanted,result);
        }
        // 0.6.12: the game reads every folder under media_soviet\workshop_wip at start, whether or
        // not a declaration still stands behind it - a folder Buildings Plus generated stays when
        // its section goes (prune is off by default), and so does one somebody built by hand. A
        // generated folder whose section is already in the result for the same resource is not
        // named a second time. The files are the game's own format, so they are read byte for
        // byte (Latin-1), not as strict UTF-8.
        static void ScanGenerated(string root,Func<string,bool> wanted,List<MissingResource> result)
        {
            string wip=WipBuildings.Root(root);
            if(wip==null||!Directory.Exists(wip))return;
            string[] folders;
            try{folders=Directory.GetDirectories(wip);}catch(Exception){return;}
            foreach(string folder in folders)
            {
                WipBuilding entry;string[] objects;
                try{entry=WipBuildings.Read(folder);objects=Directory.GetDirectories(folder);}catch(Exception){continue;}
                var seen=new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                foreach(string dir in objects)
                {
                    string file=Path.Combine(dir,"building.ini"),text;
                    if(!File.Exists(file))continue;
                    try{if(new FileInfo(file).Length>4*1024*1024)continue;text=File.ReadAllText(file,System.Text.Encoding.GetEncoding(28591));}catch(Exception){continue;}
                    foreach(string raw in text.Replace("\r\n","\n").Split('\n'))
                    {
                        string resource=ResourceOf(raw.Trim());
                        if(resource.Length==0||!wanted(resource)||!seen.Add(resource))continue;
                        bool own=entry.Origin=="buildings_plus";
                        if(own&&entry.Section.Length>0&&result.Any(m=>!m.Folder&&m.Section.Equals(entry.Section,StringComparison.OrdinalIgnoreCase)&&m.Resource.Equals(resource,StringComparison.OrdinalIgnoreCase)))continue;
                        result.Add(new MissingResource{Plugin=entry.Display,Section=entry.Id,Resource=resource,Line=raw.Trim(),Folder=true,Own=own});
                    }
                }
            }
        }
        static LoadStep StepFor(List<LoadStep> steps,string target)
        {
            if(steps==null)return null;
            return steps.FirstOrDefault(s=>s.Target.Equals(target,StringComparison.OrdinalIgnoreCase)||s.Key.Equals(target,StringComparison.OrdinalIgnoreCase));
        }
        static void ScanLines(string root,string file,LoadStep step,string[] reserved,string[] keys,Func<string,bool> wanted,List<MissingResource> result)
        {
            // What the plugin reads: plugins\<name>.ini when there is one (the effective file
            // an editor writes), else the INI beside its DLL.
            string pluginName=step.Name;
            string path=SafeFiles.Child(root,"plugins\\"+file+".ini");
            if(!File.Exists(path)&&step.Dll.Length>4)path=step.Dll.Substring(0,step.Dll.Length-4)+".ini";
            if(!File.Exists(path))return;
            LooseIni ini;try{ini=new LooseIni(SafeFiles.Text(path));}catch(Exception){return;}
            var seen=new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach(string section in ini.SectionNames())
            {
                string name=section.Trim();
                if(name.Length==0||reserved.Any(r=>r.Equals(name,StringComparison.OrdinalIgnoreCase)))continue;
                if((ini.Get(name,"enabled")??"1").Trim()=="0")continue;
                foreach(string key in keys)
                    foreach(string value in ini.GetAll(name,key))
                    {
                        // A command has fields: replace = old | new, insert = position | anchor | new,
                        // and in a Buildings Plus section a new block is one field per line. Only what
                        // is WRITTEN has to exist as a resource: the fields behind the old line or the anchor.
                        string[] parts=(value??"").Split('|');
                        int from=key=="replace"?1:key=="insert"?2:0;
                        if(from>=parts.Length)continue;
                        for(int p=from;p<parts.Length;p++)
                        {
                            string line=parts[p].Trim();
                            string resource=ResourceOf(line);
                            if(resource.Length==0||!wanted(resource))continue;
                            if(!seen.Add(name+"\n"+resource))continue;
                            result.Add(new MissingResource{Plugin=pluginName,Section=name,Resource=resource,Line=line});
                        }
                    }
            }
        }
        // The resource a building line names, "" when the line names none:
        //   $PRODUCTION <res> <rate>, $CONSUMPTION <res> <rate>, $CONSUMPTION_PER_SECOND <res> <rate>,
        //   $COST_RESOURCE <res> <amount>, $STORAGE_SPECIAL / $STORAGE_IMPORT_SPECIAL / $STORAGE_EXPORT_SPECIAL
        //   and their trash variants <class> <cap> <res>.
        public static string ResourceOf(string line)
        {
            if(String.IsNullOrWhiteSpace(line))return "";
            string[] tokens=line.Split(new[]{' ','\t'},StringSplitOptions.RemoveEmptyEntries);
            if(tokens.Length<2||!tokens[0].StartsWith("$"))return "";
            string token=tokens[0].ToUpperInvariant(),candidate="";
            if(token=="$PRODUCTION"||token=="$CONSUMPTION"||token=="$CONSUMPTION_PER_SECOND"||token=="$COST_RESOURCE")candidate=tokens[1];
            // 0.6.13: every storage line that names its resource - $STORAGE_SPECIAL, the import and
            // export forms and their ..._TRASH_BIG / ..._TRASH_SMALL variants: <class> <capacity> <resource>.
            else if(tokens.Length>=4&&Regex.IsMatch(token,@"^\$STORAGE(_[A-Z]+)*_SPECIAL(_[A-Z]+)*$"))candidate=tokens[tokens.Length-1];
            if(!Regex.IsMatch(candidate,"^[A-Za-z][A-Za-z0-9_]*$"))return "";
            return candidate;
        }
        static LoadStep StepOf(List<LoadStep> steps,CatalogEntry entry)
        {
            if(entry==null||entry.Key.Length==0)return null;
            return steps.FirstOrDefault(s=>PluginScan.SameKey(s.Key,entry.Key));
        }

        // 0.4.88: the history line of a version out of a package README - what a yellow "Update"
        // mark does not say today. The READMEs list their versions as "- **0.1.4:** ...".
        public static string Changes(string packageRoot,string version,string languageCode)
        {
            if(String.IsNullOrEmpty(packageRoot)||String.IsNullOrEmpty(version))return "";
            string[] names=languageCode=="de"?new[]{"README_DE.md","README_EN.md"}:new[]{"README_EN.md","README_DE.md"};
            foreach(string name in names)
            {
                string path;
                try{path=SafeFiles.Child(packageRoot,name);}catch(Exception){continue;}
                if(!File.Exists(path))continue;
                try
                {
                    foreach(string raw in SafeFiles.Text(path).Replace("\r\n","\n").Split('\n'))
                    {
                        string line=raw.Trim();
                        if(!line.StartsWith("- **"))continue;
                        int end=line.IndexOf(":**");
                        if(end<0)continue;
                        if(line.Substring(4,end-4).Trim()!=version)continue;
                        string text=line.Substring(end+3).Trim();
                        return text.Length>400?text.Substring(0,400)+"…":text;
                    }
                }
                catch(Exception){}
            }
            return "";
        }
    }
